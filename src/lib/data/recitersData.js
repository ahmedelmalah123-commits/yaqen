export const LEGACY_RECITER_ALIASES = {
  'ar.muhammadayyoob': 'ar.muhammadayyoub',
  'ar.khalefa': 'ar.khalifaaltunaiji',
  'ar.hussary_mujawwad_rare': 'ar.husarymujawwad',
};

export function normalizeReciterId(reciterId) {
  if (!reciterId) return 'ar.alafasy';
  const mapped = LEGACY_RECITER_ALIASES[reciterId] || reciterId;
  return recitersData.some((r) => r.id === mapped) ? mapped : 'ar.alafasy';
}

export function getReciterById(reciterId) {
  const normalized = normalizeReciterId(reciterId);
  return recitersData.find((r) => r.id === normalized) || recitersData[0];
}

export const RECITER_GROUP_ORDER = ['الأكثر استماعاً', 'ترتيل', 'تجويد'];

export const reciterGroups = RECITER_GROUP_ORDER.map((group) => ({
  group,
  reciters: recitersData.filter((r) => r.group === group),
})).filter((g) => g.reciters.length > 0);

export function getSurahAudioUrl(reciterId, surahNumber) {
  const num = Number(surahNumber);
  if (!Number.isInteger(num) || num < 1 || num > 114) {
    return null;
  }
  const reciter = getReciterById(reciterId);
  if (!reciter?.surahServerUrl) {
    return null;
  }
  const baseUrl = reciter.surahServerUrl.replace(/\/+$/, '');
  const filePart = reciter.zeroPadSurah !== false ? String(num).padStart(3, '0') : String(num);
  return `${baseUrl}/${filePart}.mp3`;
}
